using System;
using HarborBattle;
static void Check(bool condition,string message) { if(!condition) throw new Exception(message); }
var offense=new TimedLoadout<string>();var defense=new TimedLoadout<string>();
offense.Collect("RapidFire");offense.Collect("Shotgun");defense.Collect("Shield");
Check(offense.Ready=="Shotgun" && defense.Ready=="Shield","New pickup must replace only its category slot");
Check(offense.TryActivate(_=>5) && defense.TryActivate(_=>2),"One item of each category must activate simultaneously");
Check(!offense.TryActivate(_=>5),"A category must not combine active items");
Check(defense.Tick(2) && defense.Active==null && defense.Ready==null,"Expired defensive item must clear without a reserve");
Check(!offense.Tick(2) && offense.Remaining==3,"Category timers must be independent");
defense.Collect("Star");defense.TryActivate(_=>5);
offense.Collect("Laser");
Check(offense.Active==null && offense.Ready=="Laser" && offense.Remaining==0,"A pickup must replace/cancel the running item in its category");
Check(defense.Active=="Star","Replacing offense must not interrupt defense");
offense.Tick(20);Check(offense.Ready=="Laser","Stored items must wait for manual activation");
Check(offense.TryActivate(_=>2),"Stored replacement must activate on a fresh press");
offense.Tick(-10);Check(offense.Remaining==2,"Negative elapsed time must not extend an item");
Check(offense.Tick(2) && offense.Ready==null && offense.Active==null,"Expiry must not promote or auto-activate anything");
offense.Collect("Shotgun");offense.TryActivate(_=>0);Check(offense.Remaining==.1f,"Invalid duration must clamp");
offense.Clear();Check(offense.Ready==null && offense.Active==null && offense.Remaining==0,"Death/reset must clear a slot");
Console.WriteLine("PASS: category replacement, concurrent offense/defense, no reserve, no weapon combination, independent timers, manual activation, reset.");
Check(!FogExposure.Outside(32,18,32,18),"The safe boundary must remain safe");
Check(FogExposure.Outside(32.1f,0,32,18) && FogExposure.Outside(0,-18.1f,32,18),"Fog must surround all sides");
var fog=new FogExposure(); int total=0;
for(int i=0;i<50;i++) total+=fog.Tick(true,.02f,10);
Check(total==10,"One second in fog must deal exactly ten damage across physics ticks");
fog.Tick(true,.05f,10); fog.Tick(false,.1f,10);
Check(fog.Tick(true,.05f,10)==0,"Returning to safe water must reset partial exposure");
Check(fog.Tick(true,0,10)==0,"Paused simulation must not add damage");
Console.WriteLine("PASS: fog boundary, fractional damage, safe re-entry, pause.");
